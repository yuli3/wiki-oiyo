def josa(word, with_batchim, without_batchim):
    return word + (with_batchim if (ord(word[-1]) - 0xAC00) % 28 else without_batchim)

def sipsin(me_i, other_i):
    me, other = STEMS[me_i], STEMS[other_i]
    same_pol = me[3] == other[3]
    if me[2] == other[2]: return "비견" if same_pol else "겁재"
    if GEN[me[2]] == other[2]: return "식신" if same_pol else "상관"
    if CTL[me[2]] == other[2]: return "편재" if same_pol else "정재"
    if CTL[other[2]] == me[2]: return "편관" if same_pol else "정관"
    return "편인" if same_pol else "정인"

